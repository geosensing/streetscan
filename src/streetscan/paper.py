"""Write analysis output in the forms the manuscript reads: macros, tables, figures."""

import re
from pathlib import Path

from streetscan.config import FIGURE_DIR, FIGURE_DPI

DIGIT_NAMES = [
    "Zero",
    "One",
    "Two",
    "Three",
    "Four",
    "Five",
    "Six",
    "Seven",
    "Eight",
    "Nine",
]


def pct(x, digits=0):
    return f"{100 * x:.{digits}f}\\%"


def count(x):
    return f"{x:,}"


def macro_name(name):
    """LaTeX macro names may contain letters only, so digits are spelled out."""
    spelled = re.sub(r"[0-9]", lambda d: DIGIT_NAMES[int(d.group())], name)
    return re.sub(r"[^A-Za-z]", "", spelled)


def write_macros(values, path, source):
    names = [macro_name(name) for name in values]
    if len(set(names)) != len(names):
        raise ValueError("Duplicate macro names")
    lines = [f"% Generated by {source}; do not edit."]
    lines += [
        f"\\newcommand{{\\{name}}}{{{value}}}"
        for name, value in zip(names, values.values())
    ]
    Path(path).write_text("\n".join(lines) + "\n")


def latex_escape(text):
    text = text.replace("\\", "\\textbackslash{}")
    text = re.sub(r"([&%$#_{}])", r"\\\1", text)
    return re.sub(r'"([^"]*)"', r"``\1''", text)


def write_table(rows, path, align, header):
    """Write a booktabs tabular; cells must already be LaTeX-safe strings."""
    lines = [
        f"\\begin{{tabular}}{{{align}}}",
        "\\toprule",
        " & ".join(header) + " \\\\",
        "\\midrule",
        *[" & ".join(row) + " \\\\" for row in rows],
        "\\bottomrule",
        "\\end{tabular}",
    ]
    Path(path).write_text("\n".join(lines) + "\n")


def save_evidence(figure, name):
    """Save a PDF for the manuscript and a PNG for the README."""
    figure.savefig(FIGURE_DIR / f"{name}.pdf")
    figure.savefig(FIGURE_DIR / f"{name}.png", dpi=FIGURE_DPI)
